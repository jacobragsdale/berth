"""Render the whole fleet to the files under `rendered/`. Pure: the same specs always give the same bytes."""

import json
from collections.abc import Mapping

from berth import yamlio
from berth.fleet import Fleet, Instance
from berth.render import admission, airflow, controlm, k8s
from berth.render.pod import Context, Doc

ROOT = "rendered"
_README = """# rendered/

Generated by `berth render`. Do not edit anything here: CI fails if these files differ from what the specs in `apps/`
and `platform/` produce.

- `k8s/<cluster>/` is what `berth deploy` applies to that cluster, in this order: `_platform/namespaces.yaml`, the
  platform software charts (rendered at deploy time from `platform/software/`), `_platform/platform.yaml` and
  `_platform/admission.yaml`, then one directory per app environment (`<app>-<env>/`).
- `airflow/<env>/` is read by that environment's Airflow as a Git DAG bundle.
- `controlm/<env>/` is the job definitions for Control-M.
"""


def _callers(fleet: Fleet) -> dict[tuple[str, str], set[str]]:
    callers: dict[tuple[str, str], set[str]] = {}
    for instance in fleet.instances():
        for ref in instance.talks_to:
            callers.setdefault((ref.split("/", 1)[0], instance.env), set()).add(instance.app)
    return callers


def _ports(fleet: Fleet, instance: Instance) -> dict[str, int]:
    """The port of each service this instance calls. `berth check` has already proved each one exists."""
    ports: dict[str, int] = {}
    for ref in instance.talks_to:
        app, service = ref.split("/", 1)
        target = fleet.instance(app, instance.env)
        port = target.services[service].port if target is not None and service in target.services else None
        if port is not None:
            ports[ref] = port
    return ports


def _header(app: str, env: str) -> str:
    return f"# Generated by `berth render` from apps/{app} for {env}. Do not edit: change the app spec.\n"


_PLATFORM_HEADER = "# Generated by `berth render` from platform/. Do not edit.\n"


def context(fleet: Fleet, instance: Instance) -> Context:
    return Context(app=fleet.apps[instance.app].spec, instance=instance, platform=fleet.platform, ports=_ports(fleet, instance))


def instance_docs(fleet: Fleet, instance: Instance) -> list[Doc]:
    return k8s.instance_objects(context(fleet, instance), _callers(fleet).get((instance.app, instance.env), set()))


def render(fleet: Fleet) -> dict[str, str]:
    platform = fleet.platform
    files: dict[str, str] = {f"{ROOT}/README.md": _README}
    callers = _callers(fleet)
    for instance in fleet.instances():
        ctx = context(fleet, instance)
        cluster = platform.environments[instance.env].cluster
        docs = k8s.instance_objects(ctx, callers.get((instance.app, instance.env), set()))
        files[f"{ROOT}/k8s/{cluster}/{instance.namespace}/manifests.yaml"] = _header(instance.app, instance.env) + yamlio.dump_documents(docs)
        for name, workflow in sorted(instance.workflows.items()):
            if workflow.orchestrator == "airflow":
                files[f"{ROOT}/airflow/{instance.env}/{airflow.dag_id(instance.app, name)}.py"] = airflow.dag_file(ctx, name, workflow)
        on_controlm = {name: workflow for name, workflow in instance.workflows.items() if workflow.orchestrator == "controlm"}
        if on_controlm:
            files[f"{ROOT}/controlm/{instance.env}/{instance.app}.json"] = json.dumps(controlm.folders(ctx, on_controlm), indent=2) + "\n"

    for cluster in sorted(platform.clusters):
        base = f"{ROOT}/k8s/{cluster}/_platform"
        namespaces = k8s.software_namespaces(cluster, fleet.software)
        if namespaces:
            files[f"{base}/namespaces.yaml"] = _PLATFORM_HEADER + yamlio.dump_documents(namespaces)
        files[f"{base}/platform.yaml"] = _PLATFORM_HEADER + yamlio.dump_documents(k8s.cluster_objects(platform, cluster, fleet.software))
        files[f"{base}/admission.yaml"] = _PLATFORM_HEADER + yamlio.dump_documents(admission.policies(platform))
    return dict(sorted(files.items()))


def namespace_of(path: str) -> tuple[str, str] | None:
    """The (cluster, namespace) a rendered Kubernetes file belongs to, or None for shared and non-Kubernetes files."""
    parts = path.split("/")
    if len(parts) >= 4 and parts[:2] == [ROOT, "k8s"] and not parts[3].startswith("_"):  # noqa: PLR2004 - rendered/k8s/<cluster>/<namespace>/...
        return parts[2], parts[3]
    return None


def stale(expected: Mapping[str, str], actual: Mapping[str, str]) -> list[str]:
    """Paths under rendered/ that differ between what the specs produce and what is committed."""
    paths = set(expected) | {path for path in actual if path.startswith(f"{ROOT}/")}
    return sorted(path for path in paths if expected.get(path) != actual.get(path))
