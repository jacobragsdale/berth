"""Render the whole fleet to the files under `rendered/`. Pure: the same specs always give the same bytes."""

import json
from collections.abc import Mapping

from berth import yamlio
from berth.fleet import Fleet
from berth.render import airflow, controlm, k8s
from berth.render.pod import Context

ROOT = "rendered"
_README = """# rendered/

Generated by `berth render`. Do not edit anything here: CI fails if these files differ from what the specs in `apps/`
and `platform/` produce. Flux applies `k8s/<cluster>/`, Airflow reads `airflow/<env>/` as a DAG bundle, and the
main-branch pipeline deploys `controlm/<env>/` with `ctm deploy`.
"""


def _callers(fleet: Fleet) -> dict[tuple[str, str], set[str]]:
    callers: dict[tuple[str, str], set[str]] = {}
    for instance in fleet.instances():
        for ref in instance.talks_to:
            callers.setdefault((ref.split("/", 1)[0], instance.env), set()).add(instance.app)
    return callers


def _header(app: str, env: str) -> str:
    return f"# Generated by `berth render` from apps/{app} for {env}. Do not edit: change the app spec.\n"


def render(fleet: Fleet) -> dict[str, str]:
    platform = fleet.platform
    files: dict[str, str] = {f"{ROOT}/README.md": _README}
    callers = _callers(fleet)
    clusters: dict[str, dict[str, tuple[str, str]]] = {}
    for env, environment in platform.environments.items():
        clusters.setdefault(environment.cluster, {})[env] = (environment.key_vault, platform.tenant_id)

    for instance in fleet.instances():
        ctx = Context(app=fleet.apps[instance.app].spec, instance=instance, platform=platform)
        cluster = platform.environments[instance.env].cluster
        header = _header(instance.app, instance.env)
        docs = k8s.instance_objects(ctx, callers.get((instance.app, instance.env), set()))
        files[f"{ROOT}/k8s/{cluster}/{instance.namespace}/manifests.yaml"] = header + yamlio.dump_documents(docs)
        files[f"{ROOT}/k8s/{cluster}/_flux/{instance.namespace}.yaml"] = header + yamlio.dump(k8s.flux_kustomization(ctx, cluster))
        for name, workflow in sorted(instance.workflows.items()):
            if workflow.orchestrator == "airflow":
                files[f"{ROOT}/airflow/{instance.env}/{airflow.dag_id(instance.app, name)}.py"] = airflow.dag_file(ctx, name, workflow)
        on_controlm = {name: workflow for name, workflow in instance.workflows.items() if workflow.orchestrator == "controlm"}
        if on_controlm:
            files[f"{ROOT}/controlm/{instance.env}/{instance.app}.json"] = json.dumps(controlm.folders(ctx, on_controlm), indent=2) + "\n"

    for cluster, envs in sorted(clusters.items()):
        files[f"{ROOT}/k8s/{cluster}/_platform/platform.yaml"] = "# Generated by `berth render` from platform/. Do not edit.\n" + yamlio.dump_documents(k8s.cluster_objects(envs))
    return dict(sorted(files.items()))


def namespace_of(path: str) -> tuple[str, str] | None:
    """The (cluster, namespace) a rendered Kubernetes file belongs to, or None for shared and non-Kubernetes files."""
    parts = path.split("/")
    if len(parts) >= 4 and parts[:2] == [ROOT, "k8s"] and not parts[3].startswith("_"):  # noqa: PLR2004 - rendered/k8s/<cluster>/<namespace>/...
        return parts[2], parts[3]
    return None


def stale(expected: Mapping[str, str], actual: Mapping[str, str]) -> list[str]:
    """Paths under rendered/ that differ between what the specs produce and what is committed."""
    paths = set(expected) | {path for path in actual if path.startswith(f"{ROOT}/")}
    return sorted(path for path in paths if expected.get(path) != actual.get(path))
