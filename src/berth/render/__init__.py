"""Render the whole fleet to the rendered tree. Pure: the same specs always give the same bytes.

Nothing rendered is committed to main. `berth deploy` renders in memory, `berth render` writes the tree to a
directory for people to read, and the deploy pipeline publishes what it deployed to the `rendered` branch, which
Airflow and Control-M read.
"""

import json

from berth import yamlio
from berth.fleet import Fleet, Instance
from berth.model import Platform
from berth.render import admission, airflow, controlm, k8s
from berth.render.k8s import RenderError
from berth.render.pod import Context, Doc

ROOT = "rendered"  # where `berth render` writes by default; ignored by git
README = """# Rendered output

Generated by `berth render` from `apps/` and `platform/` on main. Do not edit anything here, and do not commit it
to main: the deploy pipeline renders main itself, and publishes what it deployed to the `rendered` branch.

- `k8s/<cluster>/` is what `berth deploy` applies to that cluster, in this order: `_platform/namespaces.yaml`, the
  platform software charts (rendered at deploy time from `platform/software/`), `_platform/platform.yaml` and
  `_platform/admission.yaml`, then one directory per app environment (`<app>-<env>/`).
- `airflow/<env>/` is read by that environment's Airflow as a Git DAG bundle, from the `rendered` branch.
- `controlm/<env>/` is the job definitions for Control-M.
"""


def _ports(fleet: Fleet, instance: Instance) -> dict[str, int]:
    """The port of each service this instance calls. `berth check` has already proved each one exists."""
    ports: dict[str, int] = {}
    for ref in instance.talks_to:
        app, service = ref.split("/", 1)
        target = fleet.instance(app, instance.env)
        port = target.services[service].port if target is not None and service in target.services else None
        if port is not None:
            ports[ref] = port
    return ports


def _header(app: str, env: str) -> str:
    return f"# Generated by `berth render` from apps/{app} for {env}. Do not edit: change the app spec.\n"


_PLATFORM_HEADER = "# Generated by `berth render` from platform/. Do not edit.\n"


def context(fleet: Fleet, instance: Instance) -> Context:
    return Context(app=fleet.apps[instance.app].spec, instance=instance, platform=fleet.platform, ports=_ports(fleet, instance))


def instance_docs(fleet: Fleet, instance: Instance) -> list[Doc]:
    return k8s.instance_objects(context(fleet, instance), fleet.callers().get((instance.app, instance.env), set()))


def manifests_path(cluster: str, namespace: str) -> str:
    return f"k8s/{cluster}/{namespace}/manifests.yaml"


def render(fleet: Fleet) -> dict[str, str]:
    """Every rendered file by its path in the rendered tree. A RenderError names each app environment that fails."""
    platform = fleet.platform
    files: dict[str, str] = {"README.md": README}
    callers = fleet.callers()
    problems: list[str] = []
    for instance in fleet.instances():
        ctx = context(fleet, instance)
        cluster = platform.environments[instance.env].cluster
        try:
            docs = k8s.instance_objects(ctx, callers.get((instance.app, instance.env), set()))
        except RenderError as error:
            problems.append(f"apps/{instance.app}/{instance.env}.yaml: {error}")
            continue
        files[manifests_path(cluster, instance.namespace)] = _header(instance.app, instance.env) + yamlio.dump_documents(docs)
        for name, workflow in sorted(instance.workflows.items()):
            if workflow.orchestrator == "airflow":
                files[f"airflow/{instance.env}/{airflow.dag_id(instance.app, name)}.py"] = airflow.dag_file(ctx, name, workflow)
        on_controlm = {name: workflow for name, workflow in instance.workflows.items() if workflow.orchestrator == "controlm"}
        if on_controlm:
            files[f"controlm/{instance.env}/{instance.app}.json"] = json.dumps(controlm.folders(ctx, on_controlm), indent=2) + "\n"
    if problems:
        raise RenderError("\n".join(problems))

    for cluster in sorted(platform.clusters):
        base = f"k8s/{cluster}/_platform"
        namespaces = k8s.software_namespaces(cluster, fleet.software)
        if namespaces:
            files[f"{base}/namespaces.yaml"] = _PLATFORM_HEADER + yamlio.dump_documents(namespaces)
        files[f"{base}/platform.yaml"] = _PLATFORM_HEADER + yamlio.dump_documents(k8s.cluster_objects(platform, cluster, fleet.software))
        files[f"{base}/admission.yaml"] = _PLATFORM_HEADER + yamlio.dump_documents(admission.policies(platform))
    return dict(sorted(files.items()))


def namespace_of(path: str) -> tuple[str, str] | None:
    """The (cluster, namespace) a rendered Kubernetes file belongs to, or None for shared and non-Kubernetes files."""
    parts = path.split("/")
    if len(parts) >= 3 and parts[0] == "k8s" and not parts[2].startswith("_"):  # noqa: PLR2004 - k8s/<cluster>/<namespace>/...
        return parts[1], parts[2]
    return None


def cluster_prefixes(platform: Platform, cluster: str) -> tuple[str, ...]:
    """Where one cluster's part of the rendered tree lives: its manifests, and its environments' scheduler files."""
    return (f"k8s/{cluster}/", *(f"{scheduler}/{env}/" for scheduler in ("airflow", "controlm") for env in platform.envs_on(cluster)))


def owner_of(path: str) -> tuple[str, str] | None:
    """The (app, env) a rendered file belongs to, or None for the platform's files and the README."""
    found = namespace_of(path)
    if found is not None:
        app, _, env = found[1].rpartition("-")  # environment names have no dashes, so the last one splits <app>-<env>
        return app, env
    parts = path.split("/")
    if parts[0] in {"airflow", "controlm"} and len(parts) == 3:  # noqa: PLR2004 - <scheduler>/<env>/<file>
        return parts[2].split("__", 1)[0].removesuffix(".json"), parts[1]  # app names have no underscores
    return None
