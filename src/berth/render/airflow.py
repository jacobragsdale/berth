"""One DAG file per workflow. The files are plain, readable Python so the rendered diff shows exactly what Airflow will run."""

import pprint

from berth.model import Workflow, duration_seconds
from berth.render.pod import Context, task_pod


def _identifier(task: str) -> str:
    return "task_" + task.replace("-", "_")


def _constant(task: str) -> str:
    return task.replace("-", "_").upper() + "_POD"


def _ordered(workflow: Workflow) -> list[str]:
    """Tasks in dependency order (stable by name), so the file reads top to bottom."""
    remaining = dict(sorted(workflow.tasks.items()))
    order: list[str] = []
    while remaining:
        ready = next(name for name, task in remaining.items() if set(task.depends_on) <= set(order))
        order.append(ready)
        del remaining[ready]
    return order


def dag_id(app: str, workflow: str) -> str:
    return f"{app}__{workflow}"


def dag_file(ctx: Context, name: str, workflow: Workflow) -> str:
    instance = ctx.instance
    lines = [
        f"# Generated by `berth render` from apps/{instance.app} for {instance.env}. Do not edit: change the app spec.",
        "from datetime import timedelta",
        "",
        "import pendulum",
        "from airflow.providers.cncf.kubernetes.operators.pod import KubernetesPodOperator",
        "from airflow.sdk import DAG",
        "",
    ]
    for task_name in _ordered(workflow):
        pod = {"apiVersion": "v1", "kind": "Pod"} | task_pod(ctx, name, task_name, workflow.tasks[task_name])
        lines += [f"{_constant(task_name)} = {pprint.pformat(pod, sort_dicts=False, width=120)}", ""]
    lines += [
        "",
        "with DAG(",
        f"    dag_id={dag_id(instance.app, name)!r},",
        f"    schedule={workflow.schedule!r},",
        f"    start_date=pendulum.datetime(2026, 1, 1, tz={workflow.timezone!r}),",
        "    catchup=False,",
        "    max_active_runs=1,",
        f"    tags={['berth', f'app:{instance.app}', f'env:{instance.env}']!r},",
        f"    default_args={{'owner': {', '.join(ctx.app.owners)!r}}},",
        "):",
    ]
    for task_name in _ordered(workflow):
        task = workflow.tasks[task_name]
        lines += [
            f"    {_identifier(task_name)} = KubernetesPodOperator(",
            f"        task_id={task_name!r},",
            f"        name={f'{instance.app}-{name}-{task_name}'!r},",
            f"        namespace={instance.namespace!r},",
            f"        pod_template_dict={_constant(task_name)},",
            f"        retries={task.retries},",
            "        retry_delay=timedelta(minutes=5),",
            f"        execution_timeout=timedelta(seconds={duration_seconds(task.timeout)}),",
            "        get_logs=True,",
            "        on_finish_action='delete_pod',",
            "    )",
        ]
    edges = [f"    {_identifier(parent)} >> {_identifier(task_name)}" for task_name in _ordered(workflow) for parent in workflow.tasks[task_name].depends_on]
    lines += edges
    return "\n".join(lines) + "\n"
